import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { RELEASE_CAPABILITIES } from "../web/confluence/release-capabilities.mjs";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), ".."),
  ids = new Set();
for (const entry of RELEASE_CAPABILITIES) {
  if (ids.has(entry.id)) throw Error("Duplicate capability " + entry.id);
  ids.add(entry.id);
  for (const file of entry.source)
    if (!fs.statSync(path.join(root, file)).isFile())
      throw Error("Missing capability source " + file);
}
const escape = (s) => String(s).replace(/\|/g, "\\|").replace(/\n/g, " ");
const lines = [
  "# ANIMA capability inventory",
  "",
  "Generated by `scripts/build-capabilities.mjs` from the same inventory used by Atlas. Do not edit this generated file. Code presence does not establish public deployment, funding, external service availability or a security certification.",
  "",
  "| Capability | Open | Required configuration | Actual boundary | Source |",
  "|---|---|---|---|---|",
  ...RELEASE_CAPABILITIES.map(
    (c) =>
      `| ${escape(c.label)} | ${c.route} | ${escape(c.requires.join("; ") || "Browser runtime")} | ${escape(c.boundary)} | ${c.source.map((p) => "`" + p + "`").join(", ")} |`,
  ),
  "",
];
fs.writeFileSync(path.join(root, "docs/CAPABILITIES.md"), lines.join("\n"));
fs.writeFileSync(path.join(root,"docs/genesis/CURRENT-CAPABILITIES.md"),lines.join("\n"));
console.log(`Generated ${ids.size} capabilities from the runtime registry.`);
