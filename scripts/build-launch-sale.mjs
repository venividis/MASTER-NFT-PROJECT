import fs from 'node:fs';
import path from 'node:path';
import {keccak256} from 'ethers';
import {verifyCompilation} from './lib/compiler-artifacts.mjs';

const root=path.resolve(import.meta.dirname,'..');
const index=verifyCompilation(root),result={};
for(const name of ['GenesisLaunchpad','WorldLedger','TimeVault','NativeMarket','GenesisToken']){
  const identity=index.aliases[name],record=index.artifacts[identity];
  if(!record||identity!==`contracts/src/protocol/${name}.sol:${name}`)throw Error('Community contract source identity changed: '+name);
  const artifact=JSON.parse(fs.readFileSync(path.join(root,'contracts/artifacts',record.file),'utf8'));
  const immutableGroups=Object.values(artifact.immutableReferences),masks=immutableGroups.flat();let code=artifact.deployedBytecode.slice(2);
  for(const m of masks)code=code.slice(0,m.start*2)+'0'.repeat(m.length*2)+code.slice((m.start+m.length)*2);
  result[name]={abi:artifact.abi,compiler:artifact.compiler,evmVersion:index.settings.evmVersion,bytes:code.length/2,masks,immutableGroups,normalizedHash:keccak256('0x'+code),...(name==='GenesisToken'?{}:{bytecode:artifact.bytecode,creationHash:keccak256(artifact.bytecode)})};
}
const target=path.join(root,'web/launchpad/sale-artifacts.mjs');fs.mkdirSync(path.dirname(target),{recursive:true});
fs.writeFileSync(target,'// Generated by scripts/build-launch-sale.mjs from verified canonical Solidity artifacts.\nexport const SALE_ARTIFACTS = '+JSON.stringify(result)+';\n');
console.log(`Built ${Object.keys(result).length} verified community launch artifacts (${index.settings.evmVersion}).`);
