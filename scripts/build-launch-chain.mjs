// Recreate browser deployment bytecode only from the verified pinned v4 compilation.
import fs from 'node:fs';
import path from 'node:path';
import {keccak256} from '../web/vendor/ethers.min.js';
import {verifyV4Compilation} from './lib/v4-compilation.mjs';
import {ARTIFACTS} from '../web/v4/artifacts.mjs';
import {normalizeRuntime} from '../web/v4/client.mjs';

const projectRoot=path.resolve(import.meta.dirname,'..');
const manifest=verifyV4Compilation(projectRoot);
const artifactsRoot=path.join(projectRoot,'integrations/console/protocol/v4-hook/artifacts');
const deployments={};
for(const name of ['GenesisV4Launchpad','GenesisV4Router']){
 const artifact=JSON.parse(fs.readFileSync(path.join(artifactsRoot,name+'.json'),'utf8'));
 if(artifact.contractName!==name||!/^0x(?:[a-f0-9]{2})+$/i.test(artifact.bytecode))throw Error('Invalid deployment artifact: '+name);
 if(normalizeRuntime(artifact.deployedBytecode,ARTIFACTS[name])!==ARTIFACTS[name].normalizedHash)throw Error('Rebuild web/v4/artifacts.mjs from this verified compilation before creating deployment code.');
 const source=manifest.sources[artifact.sourceName];
 if(!source?.sha256)throw Error('Missing verified source provenance: '+artifact.sourceName);
 deployments[name]={bytecode:artifact.bytecode,creationHash:keccak256(artifact.bytecode),compiler:artifact.compiler,sourceName:artifact.sourceName,sourceSha256:source.sha256};
}
const output=path.join(projectRoot,'web/launchpad/deployments.mjs');
fs.mkdirSync(path.dirname(output),{recursive:true});
fs.writeFileSync(output,'// Generated by scripts/build-launch-chain.mjs from the verified pinned Solidity compilation.\n// Creation hashes and source fingerprints are checked before generating; deployed runtime is independently verified after mining.\nexport const DEPLOYMENTS='+JSON.stringify(deployments)+';\n');
console.log(JSON.stringify({output:path.relative(projectRoot,output),compiler:manifest.compiler,contracts:Object.keys(deployments)}));
