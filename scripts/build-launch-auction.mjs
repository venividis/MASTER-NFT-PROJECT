import fs from 'node:fs';
import path from 'node:path';
import solc from 'solc';
import {keccak256, toUtf8Bytes} from 'ethers';
import {verifyCompilation} from './lib/compiler-artifacts.mjs';

const root = path.resolve(import.meta.dirname, '..');
const index = verifyCompilation(root);
const name = 'ContinuousClearingAuction';
const source = 'contracts/src/extensions/markets/ContinuousClearingAuction.sol';
const identity = `${source}:${name}`;
const record = index.artifacts[identity];
if (!record || index.aliases[name] !== identity) throw Error('Auction source identity changed.');
if (solc.version() !== index.compiler) throw Error('Use the compiler that produced the verified artifacts.');
const artifact = JSON.parse(fs.readFileSync(path.join(root, 'contracts/artifacts', record.file), 'utf8'));

// Parse the identical ordered source inventory with the identical compiler. AST IDs
// identify each compiler immutable reference without relying on declaration order.
const sources = Object.fromEntries(Object.keys(index.sources).map(file => [file, {content: fs.readFileSync(path.join(root, file), 'utf8')}]));
const parsed = JSON.parse(solc.compile(JSON.stringify({language: index.language, sources, settings: {...index.settings, outputSelection: {'*': {'': ['ast']}}}})));
const errors = (parsed.errors || []).filter(error => error.severity === 'error');
if (errors.length) throw Error(errors.map(error => error.formattedMessage).join('\n'));
const declarations = new Map();
function inspect(value) {
  if (!value || typeof value !== 'object') return;
  if (value.nodeType === 'VariableDeclaration' && value.mutability === 'immutable') declarations.set(String(value.id), value.name);
  for (const item of Object.values(value)) if (item && typeof item === 'object') {
    if (Array.isArray(item)) item.forEach(inspect); else inspect(item);
  }
}
inspect(parsed.sources[source]?.ast);
const immutables = {};
for (const [id, locations] of Object.entries(artifact.immutableReferences)) {
  const field = declarations.get(id);
  if (!field || immutables[field] || !locations.length) throw Error('Unrecognized auction immutable reference: ' + id);
  immutables[field] = locations;
}
const required = ['seller', 'saleToken', 'lotSize', 'totalLots', 'startBlock', 'endBlock', 'reservePrice'];
if (JSON.stringify(Object.keys(immutables).sort()) !== JSON.stringify(required.sort())) throw Error('Auction immutable terms changed. Review the browser verifier.');
const masks = Object.values(immutables).flat();
let code = artifact.deployedBytecode.slice(2);
for (const mask of masks) {
  if (mask.length !== 32 || mask.start < 0 || mask.start + mask.length > code.length / 2) throw Error('Invalid auction immutable location.');
  code = code.slice(0, mask.start * 2) + '0'.repeat(mask.length * 2) + code.slice((mask.start + mask.length) * 2);
}
const result = {
  name,
  label: 'ANIMA streaming auction',
  compiler: artifact.compiler,
  evmVersion: index.settings.evmVersion,
  optimizerRuns: index.settings.optimizer.runs,
  sourceHashes: Object.fromEntries(Object.keys(artifact.metadata.sources).map(file => [file, keccak256(toUtf8Bytes(sources[file].content))])),
  abi: artifact.abi,
  bytecode: artifact.bytecode,
  creationHash: keccak256(artifact.bytecode),
  runtime: artifact.deployedBytecode,
  bytes: code.length / 2,
  normalizedHash: keccak256('0x' + code),
  masks,
  immutables,
};
const target = path.join(root, 'web/launchpad/auction-artifacts.mjs');
fs.mkdirSync(path.dirname(target), {recursive: true});
fs.writeFileSync(target, '// Generated by scripts/build-launch-auction.mjs from verified canonical Solidity artifacts.\nexport const AUCTION_ARTIFACT = Object.freeze(' + JSON.stringify(result) + ');\nexport const AUCTION_ARTIFACTS = Object.freeze({ContinuousClearingAuction: AUCTION_ARTIFACT});\n');
console.log(`Built verified ANIMA streaming auction artifacts (${index.settings.evmVersion}).`);
