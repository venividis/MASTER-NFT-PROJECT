import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {keccak256} from 'ethers';
import {verifyV4Compilation} from './lib/v4-compilation.mjs';
const root=path.resolve(import.meta.dirname,'..');
verifyV4Compilation(root);
// This package has no compilation manifest. Rebuild its source before reading
// OwnerFeeRouter so a changed fee policy cannot retain a stale browser artifact.
createRequire(import.meta.url)('../integrations/console/protocol/fee-router/scripts/compile.cjs').compile();
const names=['GenesisV4HookLaunchpad','OwnerV4FeeHook','HookCreate2Factory','OwnerFeeRouter'];
const output={};
for(const name of names){
  const area=name==='OwnerFeeRouter'?'fee-router':'v4-hook';
  const a=JSON.parse(fs.readFileSync(path.join(root,'integrations/console/protocol',area,'artifacts',name+'.json')));
  const immutableGroups=Object.values(a.immutableReferences||{}),masks=immutableGroups.flat();
  let code=a.deployedBytecode.slice(2);
  for(const m of masks)code=code.slice(0,m.start*2)+'0'.repeat(m.length*2)+code.slice((m.start+m.length)*2);
  output[name]={abi:a.abi,bytecode:a.bytecode,normalizedHash:keccak256('0x'+code),bytes:code.length/2,masks,immutableGroups,compiler:a.compiler};
}
fs.mkdirSync(path.join(root,'web/launchpad'),{recursive:true});
fs.writeFileSync(path.join(root,'web/launchpad/hook-artifacts.mjs'),'// Generated by scripts/build-hook-launch.mjs from pinned compilation artifacts.\nexport const HOOK_ARTIFACTS='+JSON.stringify(output)+';\n');
console.log('Hook launch bytecode, ABI and runtime fingerprints built.');
